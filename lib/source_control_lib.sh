#!/bin/bash
#
# Repository validation and Git pre-commit guard utilities for Antigravity Sandbox.

[[ -n "${_AGY_CMD_SOURCE_CONTROL_LIB_LOADED:-}" ]] && return 0
_AGY_CMD_SOURCE_CONTROL_LIB_LOADED=1

LIB_DIR="${LIB_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)}"
source "${LIB_DIR}/sandbox_config.sh"
source "${LIB_DIR}/sandbox_lib.sh"

#######################################
# Run git commands in a specific repo path without invoking hooks.
# Arguments:
#   Repository directory path, followed by git arguments.
#######################################
git_in_repo() {
  local repo_path="$1"
  shift
  git -C "${repo_path}" -c core.hooksPath=/dev/null -c core.fsmonitor=false "$@"
}

#######################################
# Ensure target directory is not inside the sandbox home or a dangerous root.
# Globals:
#   AGY_CLI_NAME
#   CANONICAL_SHOME
#   HOME
# Arguments:
#   Target directory path.
#######################################
check_safe_directory_path() {
  local target_dir="$1"
  local canonical_home
  canonical_home="$(cd "${HOME:-/tmp}" && pwd -P)"
  ensure_sandbox_layout

  if [[ "${target_dir}" == "${CANONICAL_SHOME}"* ]]; then
    err "Refusing to run host ${AGY_CLI_NAME:-agy-workflow} commands inside the sandbox directory (${target_dir})!"
  fi
  if [[ "${target_dir}" == "/" || "${target_dir}" == "/Users" || "${target_dir}" == "${canonical_home}" ]]; then
    err "Refusing to initialize or operate directly in '${target_dir}'. Please cd into a project directory."
  fi
}

#######################################
# Verify and initialize TRUSTED_REPO, REPO_NAME, and overlay registry metadata.
# Globals:
#   OVERLAYS_DIR
#   REGISTRY_DIR
#   REPO_NAME
#   REPO_OVERLAY_DIR
#   REPO_REGISTRY_FILE
#   TRUSTED_REPO
# Arguments:
#   Auto-bootstrap boolean ("true" or "false").
#######################################
require_trusted_repo() {
  local auto_bootstrap="${1:-false}"
  local cur_dir
  cur_dir="$(pwd -P)"

  check_safe_directory_path "${cur_dir}"

  if [[ "${auto_bootstrap}" == "true" && ! -d "${cur_dir}/.git" ]]; then
    info "No '.git' directory in '${cur_dir}'. Running 'git init -b main'..."
    git init -b main "${cur_dir}"
  elif ! git rev-parse --show-toplevel &>/dev/null; then
    err "Current directory is not inside a Git repository. Run 'agy-workflow start' or 'agy-workflow init' to bootstrap one."
  fi

  local raw_top
  raw_top="$(git rev-parse --show-toplevel)"
  TRUSTED_REPO="$(cd "${raw_top}" && pwd -P)"

  check_safe_directory_path "${TRUSTED_REPO}"

  if ! git_in_repo "${TRUSTED_REPO}" rev-parse --verify HEAD &>/dev/null; then
    if [[ "${auto_bootstrap}" == "true" ]]; then
      info "Repository '${TRUSTED_REPO}' has no commits yet. Creating initial root commit..."
      git_in_repo "${TRUSTED_REPO}" commit --allow-empty -m "chore: initial repository bootstrap"
    else
      err "Repository '${TRUSTED_REPO}' has no commits yet. Run 'agy-workflow init' or 'agy-workflow start' to auto-create an initial commit."
    fi
  fi

  REPO_NAME="$(basename "${TRUSTED_REPO}")"
  REPO_OVERLAY_DIR="${OVERLAYS_DIR}/${REPO_NAME}"
  REPO_REGISTRY_FILE="${REGISTRY_DIR}/${REPO_NAME}.json"
}

#######################################
# Install host-side pre-commit hook guard to block staging CI/CD & metadata files.
# Arguments:
#   Repository path and state directory for backups.
#######################################
install_host_pre_commit_guard() {
  local repo="$1"
  local state_dir="$2"
  local hooks_dir="${repo}/.git/hooks"
  local hook_file="${hooks_dir}/pre-commit"
  local backup_file="${state_dir}/host-pre-commit-backup"

  mkdir -p "${hooks_dir}" "${state_dir}"

  if [[ -f "${hook_file}" ]] \
      && ! grep -qE "Auto-generated by (git-agy|agy-workflow|agy-sandbox)" "${hook_file}" 2>/dev/null; then
    cp -p "${hook_file}" "${backup_file}"
  fi

  git -C "${repo}" config --local core.hooksPath .git/hooks 2>/dev/null || true

  cat > "${hook_file}" <<EOF
#!/usr/bin/env bash
# Auto-generated by agy-workflow: Host pre-commit guard against CI/CD and metadata injection
set -e

if [ -x "${backup_file}" ]; then
    "${backup_file}" "\$@"
fi

if [ "\${AGY_ALLOW_PROTECTED_COMMIT:-0}" = "1" ]; then
    exit 0
fi

PROTECTED_REGEX='^(\.github/|\.circleci/|\.buildkite/|\.husky/|\.vscode/|\.idea/|[._]agents?/|\.gitlab-ci\.ya?ml$|Jenkinsfile$|azure-pipelines\.yml$|\.travis\.yml$|cloudbuild\.yaml$|bitbucket-pipelines\.yml$|\.gitattributes$|\.gitmodules$|\.gitconfig$|\.pre-commit-config\.yaml$|\.envrc$|\.mise\.toml$|\.continuerules$|hooks\.json$|mcp_config\.json$|config\.worktree$|\.env($|\.))'

staged_protected="\$(git diff --cached --name-only | grep -E "\$PROTECTED_REGEX" | grep -vE '^\.env\.(example|sample|template|dist)\$' || true)"
if [ -n "\$staged_protected" ]; then
    echo "[agy-workflow] ERROR: Staged changes touch protected CI/CD, IDE, or metadata path(s):" >&2
    echo "\$staged_protected" | sed 's/^/  - /' >&2
    echo "[agy-workflow] If you intentionally modified these files on the host, re-run with:" >&2
    echo "  AGY_ALLOW_PROTECTED_COMMIT=1 git commit ..." >&2
    exit 1
fi
EOF
  chmod +x "${hook_file}"
}

#######################################
# Register repository with Direct Source Mount sandbox and configure guards.
# Globals:
#   CODE_SERVER_PORT
#   REGISTRY_DIR
#   REPO_NAME
#   REPO_OVERLAY_DIR
#   REPO_REGISTRY_FILE
#   TRUSTED_REPO
# Arguments:
#   Optional target directory path.
#######################################
register_sandbox_repo() {
  local target_dir="${1:-}"
  if [[ -n "${target_dir}" ]]; then
    mkdir -p "${target_dir}"
    cd "${target_dir}"
  fi
  require_trusted_repo "true"
  info "Configuring Direct Source Mount + Read-Only Metadata Sandbox for '${REPO_NAME}'..."

  mkdir -p "${REPO_OVERLAY_DIR}" "${REGISTRY_DIR}"
  cat > "${REPO_REGISTRY_FILE}" <<EOF
{
  "name": "${REPO_NAME}",
  "host_repo": "${TRUSTED_REPO}",
  "created_at": "$(date -u +'%Y-%m-%dT%H:%M:%SZ')"
}
EOF

  install_host_pre_commit_guard "${TRUSTED_REPO}" "${REPO_OVERLAY_DIR}"
  ensure_agy_project_config "${REPO_NAME}"
  generate_overlay_compose_override

  if command -v docker &>/dev/null && docker inspect -f '{{.State.Running}}' agy-agent-sandbox 2>/dev/null | grep -q "true"; then
    if ! is_repo_mounted_in_container; then
      info "New host repository mounted; updating sandbox pod configuration..."
      compose_cmd up -d
    fi
  fi

  ok "Repository '${REPO_NAME}' registered in Direct Source Mount sandbox:"
  echo "  Trusted Host Repo : ${TRUSTED_REPO} (:rw mount at /workspaces/${REPO_NAME})"
  echo "  Read-Only Guards  : .git:ro, .git/hooks:ro, .github:ro, .vscode:ro, .env*:ro"
  echo "  Host Commit Guard : .git/hooks/pre-commit (blocks unauthorized CI/CD & metadata commits)"
  echo "  Repo IDE URL      : http://127.0.0.1:${CODE_SERVER_PORT:-8443}/?folder=/workspaces/${REPO_NAME}"
}
